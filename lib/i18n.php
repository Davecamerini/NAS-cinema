declare(strict_types=1);

function cinema_app_lang(): string
{
    $lang = (string) cinema_config_get('app_language', 'en');
    return $lang === 'it' ? 'it' : 'en';
}

function cinema_t(string $key, array $replace = []): string
{
    $lang = cinema_app_lang();
    $all = cinema_translations();
    $text = $all[$lang][$key] ?? $all['en'][$key] ?? $key;
    foreach ($replace as $name => $value) {
        $text = str_replace('{' . $name . '}', (string) $value, $text);
    }
    return $text;
}

